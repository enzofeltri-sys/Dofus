// Pause (demande d'Enzo) : ordre des sorts modifiable en combat, butin ramassé, quitter le combat.
import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errors = [];
p.on('pageerror', (e) => errors.push('[pageerror] ' + e.message));
p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') console.log('[console]', m.text()); });
await p.goto('http://localhost:5173/');
await p.evaluate(async () => {
  const pr = await import('/src/game/progression.ts');
  const inv = await import('/src/game/inventory.ts');
  localStorage.setItem('dofus-enzo-save', JSON.stringify({ v: 5, runs: 3, wins: 1, bestRoom: 5, bestWinTime: 200, xp: 0, resources: {}, profile: { ...pr.defaultProfile(), xp: pr.XP_TABLE[12] }, inventory: inv.starterInventory(), done: ['champs'], area: 'champs' }));
});
await p.reload();
await p.waitForFunction(() => document.getElementById('loading')?.classList.contains('done'), null, { timeout: 60000 });
await p.waitForSelector('.camp:not([hidden]) .enter', { timeout: 20000 });
await p.click('.camp .enter');
await p.waitForTimeout(1200);
await p.evaluate(async () => {
  const g = window.__game;
  const { applyCard } = await import('/src/game/cards.ts');
  for (const id of ['absorption', 'supplice', 'attirance']) applyCard(g, { kind: 'spell', spell: id });
  const { ITEMS } = await import('/src/game/data/items.ts');
  const ids = Object.keys(ITEMS).map(Number);
  g.stats.loot[ids[0]] = 3;
  g.stats.loot[ids[5]] = 1;
  g.stats.xp = 42;
});
await p.waitForTimeout(500);
await p.waitForTimeout(1500);
console.log('boutons pause :', await p.evaluate(() => [...document.querySelectorAll('.pause')].map((e) => e.className + ' dans ' + e.parentElement.className).join(' | ')));
console.log('juste après le clic :', await p.evaluate(() => { document.querySelector('.top .pause').click(); return document.querySelector('.pausemenu').hidden; }));
await p.waitForTimeout(600);
console.log('menu de pause ouvert :', await p.evaluate(() => !document.querySelector('.pausemenu').hidden), '| overlay :', await p.evaluate(() => !document.querySelector('.overlay').hidden));
const order = () => p.evaluate(() => window.__game.run.slots.map((s) => s?.id ?? '-').join(','));
console.log('avant :', await order());
await p.click('.pm-slots .pk-slot[data-s="0"]');
await p.click('.pm-slots .pk-slot[data-s="2"]');
console.log('après échange 1↔3 :', await order());
await p.screenshot({ path: 'shots/pause.png' });
await p.click('.pausemenu .quit');
await p.waitForTimeout(200);
await p.screenshot({ path: 'shots/pause_quitter.png' });
await p.click('.pausemenu .quit');
await p.waitForTimeout(1500);
console.log('bilan affiché :', await p.evaluate(() => !document.querySelector('.summary').hidden), '| titre :', await p.textContent('.summary h2'));
await p.screenshot({ path: 'shots/pause_bilan.png' });
console.log(errors.join('\n') || 'aucune erreur');
await b.close();
