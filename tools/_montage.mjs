import { chromium } from 'playwright-core';
import { writeFileSync } from 'node:fs';
const dir = process.argv[2], names = process.argv[4].split(',');
const html = `<body style="margin:0;background:#fff;display:flex;flex-wrap:wrap;width:1000px;font:12px sans-serif">${names.map((n) => { const [g, label] = n.split(':'); return `<div style="width:200px;text-align:center"><img src="file://${dir}/g${g}.png" style="width:190px;height:190px;image-rendering:auto"><br>${label}</div>`; }).join('')}</body>`;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const p = await b.newPage({ viewport: { width: 1000, height: 400 } });
writeFileSync(dir + '/_m.html', html);
await p.goto('file://' + dir + '/_m.html');
await p.waitForTimeout(400);
await p.screenshot({ path: process.argv[3], fullPage: true });
await b.close();
